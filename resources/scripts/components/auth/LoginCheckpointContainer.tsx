import React, { useState } from 'react';
import { Link, Navigate, useLocation } from 'react-router-dom';
import loginCheckpoint from '@/api/auth/loginCheckpoint';
import LoginFormContainer from '@/components/auth/LoginFormContainer';
import { ActionCreator } from 'easy-peasy';
import { useFormikContext, withFormik } from 'formik';
import useFlash from '@/plugins/useFlash';
import { FlashStore } from '@/state/flashes';
import Field from '@/components/elements/Field';
import tw from 'twin.macro';
import Button from '@/components/elements/Button';
import RememberSwitch from '@/components/auth/RememberSwitch';
import { t } from '@/i18n';

interface Values {
    code: string;
    recoveryCode: '';
    trustDevice: boolean;
}

type Props = {
    token: string;
    canTrustDevice: boolean;
    trustDays: number;
    clearAndAddHttpError: ActionCreator<FlashStore['clearAndAddHttpError']['payload']>;
};

const LoginCheckpointContainer = ({ canTrustDevice, trustDays }: { canTrustDevice: boolean; trustDays: number }) => {
    const { isSubmitting, setFieldValue, values } = useFormikContext<Values>();
    const [isMissingDevice, setIsMissingDevice] = useState(false);

    return (
        <LoginFormContainer title={t('Device Checkpoint')}>
            <div css={tw`mt-6`}>
                <Field
                    light
                    name={isMissingDevice ? 'recoveryCode' : 'code'}
                    title={isMissingDevice ? t('Recovery Code') : t('Authentication Code')}
                    description={
                        isMissingDevice
                            ? t(
                                  'Enter one of the recovery codes generated when you setup 2-Factor authentication on this account in order to continue.'
                              )
                            : t('Enter the two-factor token generated by your device.')
                    }
                    type={'text'}
                    autoComplete={'one-time-code'}
                    autoFocus
                />
            </div>
            {canTrustDevice && !isMissingDevice && (
                <RememberSwitch
                    className={'mt-5'}
                    checked={values.trustDevice}
                    onChange={(value) => setFieldValue('trustDevice', value)}
                    disabled={isSubmitting}
                >
                    {t('Trust this device for {{count}} days', { count: trustDays })}
                    <span className={'block text-xs text-gray-500'}>
                        {t(
                            'Only your password is asked for on this browser until then. Do not use this on shared computers.'
                        )}
                    </span>
                </RememberSwitch>
            )}
            <div css={tw`mt-6`}>
                <Button size={'xlarge'} type={'submit'} disabled={isSubmitting} isLoading={isSubmitting}>
                    {t('Continue')}
                </Button>
            </div>
            <div css={tw`mt-6 text-center`}>
                <span
                    onClick={() => {
                        setFieldValue('code', '');
                        setFieldValue('recoveryCode', '');
                        setIsMissingDevice((s) => !s);
                    }}
                    className={'cursor-pointer text-sm text-gray-400 hover:text-raptor-400 no-underline'}
                >
                    {!isMissingDevice ? t("I've Lost My Device") : t('I Have My Device')}
                </span>
            </div>
            <div css={tw`mt-6 text-center`}>
                <Link to={'/auth/login'} className={'text-sm text-gray-400 hover:text-raptor-400 no-underline'}>
                    {t('Return to Login')}
                </Link>
            </div>
        </LoginFormContainer>
    );
};

const EnhancedForm = withFormik<Props, Values>({
    handleSubmit: ({ code, recoveryCode, trustDevice }, { setSubmitting, props: { clearAndAddHttpError, token } }) => {
        loginCheckpoint(token, code, recoveryCode, trustDevice)
            .then((response) => {
                if (response.complete) {
                    // @ts-expect-error this is valid
                    window.location = response.intended || '/';
                    return;
                }

                setSubmitting(false);
            })
            .catch((error) => {
                console.error(error);
                setSubmitting(false);
                clearAndAddHttpError({ error });
            });
    },

    mapPropsToValues: () => ({
        code: '',
        recoveryCode: '',
        trustDevice: false,
    }),
})(({ canTrustDevice, trustDays }: Props) => (
    <LoginCheckpointContainer canTrustDevice={canTrustDevice} trustDays={trustDays} />
));

export default () => {
    const location = useLocation();
    const { clearAndAddHttpError } = useFlash();

    const state = location.state as { token?: string; canTrustDevice?: boolean; trustDays?: number } | null;
    if (!state?.token) {
        return <Navigate to={'/auth/login'} replace />;
    }

    return (
        <EnhancedForm
            clearAndAddHttpError={clearAndAddHttpError}
            token={state.token}
            canTrustDevice={!!state.canTrustDevice}
            trustDays={state.trustDays || 30}
        />
    );
};
